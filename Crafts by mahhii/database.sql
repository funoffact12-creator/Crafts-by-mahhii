CREATE DATABASE IF NOT EXISTS crafts_by_mahhi
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE crafts_by_mahhi;

CREATE TABLE IF NOT EXISTS shop_settings (
  id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
  shop_name VARCHAR(120) NOT NULL DEFAULT 'My Shop',
  tagline VARCHAR(180) NOT NULL DEFAULT '',
  shop_strip VARCHAR(255) NOT NULL DEFAULT '',
  tag_note VARCHAR(255) NOT NULL DEFAULT '',
  whatsapp VARCHAR(32) NOT NULL DEFAULT '',
  delivery VARCHAR(255) NOT NULL DEFAULT '',
  palette VARCHAR(20) NOT NULL DEFAULT 'lavender',
  code_hash CHAR(64) NOT NULL DEFAULT '',
  next_code INT UNSIGNED NOT NULL DEFAULT 1,
  initialized TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS products (
  id VARCHAR(64) NOT NULL PRIMARY KEY,
  code INT UNSIGNED NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  price INT UNSIGNED NOT NULL,
  category VARCHAR(80) NOT NULL DEFAULT '',
  hue SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  image_data MEDIUMTEXT NOT NULL,
  sold_out TINYINT(1) NOT NULL DEFAULT 0,
  is_example TINYINT(1) NOT NULL DEFAULT 0,
  INDEX idx_products_category (category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

